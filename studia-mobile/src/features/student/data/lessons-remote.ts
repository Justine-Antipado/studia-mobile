// lessons-remote.ts: student lessons (materials) from Supabase. Opening a lesson records a view,
// which is what class progress counts (class_progress view). Transcripts and AI summaries are
// written by the server pipeline; the app only reads them.
import { appError, fail, type Result } from "@/core/data/errors/app-error";
import { toAttachment, type StoredFile } from "@/core/data/supabase/file-upload";
import { db, guard, must, myId } from "@/core/data/supabase/remote";
import type { VideoLink } from "@/core/types/content";
import type { LessonRepository } from "@/features/student/data/lessons-repository";
import type { Lesson, ProcessingState } from "@/features/student/types/student";

const SELECT =
  "id, class_id, title, kind, duration_sec, processing, posted_at, video_url, video_provider, video_id, file:files(id, original_name, kind, size_bytes), transcript:material_transcript_lines(id, start_sec, body), summaries:material_summaries(mode, tldr, bullets, regen_count)";
const MAX_REGENS = 3;

type Row = {
  id: string;
  class_id: string;
  title: string;
  kind: Lesson["kind"];
  duration_sec: number | null;
  processing: ProcessingState;
  posted_at: string;
  video_url: string | null;
  video_provider: "youtube" | "other" | null;
  video_id: string | null;
  file: StoredFile | null;
  transcript: { id: string; start_sec: number; body: string }[];
  summaries: { mode: string; tldr: string | null; bullets: unknown; regen_count: number }[];
};

export function durationLabel(sec: number | null): string | null {
  if (sec === null || sec <= 0) return null;
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return `${m}:${String(s).padStart(2, "0")}`;
}

function toLink(r: { video_url: string | null; video_provider: "youtube" | "other" | null; video_id: string | null }): VideoLink | null {
  return r.video_url && r.video_provider ? { provider: r.video_provider, url: r.video_url, videoId: r.video_id } : null;
}

function toLesson(r: Row): Lesson {
  const tldr = r.summaries.find((s) => s.tldr)?.tldr ?? null;
  const bulletsRaw = r.summaries.find((s) => Array.isArray(s.bullets))?.bullets;
  const bullets = Array.isArray(bulletsRaw) ? bulletsRaw.filter((b): b is string => typeof b === "string") : [];
  const used = r.summaries.reduce((m, s) => Math.max(m, s.regen_count ?? 0), 0);
  return {
    id: r.id,
    classId: r.class_id,
    title: r.title,
    kind: r.kind,
    link: toLink(r),
    durationLabel: durationLabel(r.duration_sec),
    attachment: r.file ? toAttachment(r.file) : null,
    processing: r.processing,
    transcript: [...r.transcript].sort((a, b) => a.start_sec - b.start_sec).map((t) => ({ id: t.id, startSec: t.start_sec, text: t.body })),
    aiSummary: tldr || bullets.length ? { tldr: tldr ?? "", bullets } : null,
    regensLeft: Math.max(0, MAX_REGENS - used),
    postedAt: r.posted_at,
  };
}

async function load(classId: string, id: string | null): Promise<Lesson[]> {
  let q = db().from("materials").select(SELECT).eq("class_id", classId).is("deleted_at", null).order("posted_at", { ascending: false });
  if (id) q = q.eq("id", id);
  return (must(await q) as Row[]).map(toLesson);
}

async function recordView(materialId: string): Promise<void> {
  try {
    const me = await myId();
    const now = new Date().toISOString();
    const found = must(await db().from("material_views").select("id, view_count, completed_at").eq("material_id", materialId).eq("student_id", me).maybeSingle()) as
      | { id: string; view_count: number; completed_at: string | null }
      | null;
    if (!found) {
      await db().from("material_views").insert({ material_id: materialId, student_id: me, completed_at: now });
    } else {
      await db()
        .from("material_views")
        .update({ view_count: found.view_count + 1, last_seen_at: now, completed_at: found.completed_at ?? now })
        .eq("id", found.id);
    }
  } catch {
    // A failed view tick must never block opening the lesson.
  }
}

export class RemoteLessonRepository implements LessonRepository {
  listByClass(classId: string): Promise<Result<Lesson[]>> {
    return guard(() => load(classId, null));
  }

  get(classId: string, id: string): Promise<Result<Lesson | null>> {
    return guard(async () => {
      const lesson = (await load(classId, id))[0] ?? null;
      if (lesson) void recordView(id);
      return lesson;
    });
  }

  async regenerateSummary(): Promise<Result<Lesson>> {
    return fail(appError("conflict", "AI summaries are generated by the server and can't be regenerated from the app yet.", false));
  }
}
